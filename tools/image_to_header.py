#!/usr/bin/env python3
"""
Session 6 — turn image files into C arrays for on-device vision.

run_classifier() needs a populated pixel buffer, NOT a .jpg — you can't hand
the chip an image file. So we bake a few pictures into the firmware as arrays.

Usage:
    pip install pillow
    python tools/image_to_header.py person.jpg empty.jpg -o include/test_images.h

Produces, for each input image and each size in SIZES, an RGB C array:
    const uint8_t person_96[96 * 96 * 3] = { r, g, b, r, g, b, ... };

The image is prepared the way Edge Impulse's "Fit shortest axis" resize mode
does it: centre-cropped to a square, then scaled. The Person Detection model
from the session-6 lab expects RGB, so the arrays are RGB, three bytes per pixel.

Feed one to your model at the matching input resolution and time it with millis().
"""
import argparse
import os
from PIL import Image, ImageOps

SIZES = [48, 96, 160]   # the resolutions you'll test the wall at


def to_array(path, size):
    img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")  # honour the phone's rotation
    w, h = img.size
    side = min(w, h)                                                  # centre-crop to a square
    left, top = (w - side) // 2, (h - side) // 2
    img = img.crop((left, top, left + side, top + side))
    img = img.resize((size, size), Image.LANCZOS)
    return [channel for pixel in img.getdata() for channel in pixel]  # r, g, b, r, g, b, ...


def c_name(path, size):
    base = os.path.splitext(os.path.basename(path))[0]
    safe = "".join(c if c.isalnum() else "_" for c in base)
    return f"{safe}_{size}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("images", nargs="+", help="input image files")
    ap.add_argument("-o", "--out", default="include/test_images.h")
    args = ap.parse_args()

    lines = [
        "// Auto-generated by tools/image_to_header.py — do not edit by hand.",
        "// RGB test images (3 bytes per pixel, row by row) baked in as C arrays.",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for path in args.images:
        for size in SIZES:
            data = to_array(path, size)
            name = c_name(path, size)
            rows = [", ".join(str(v) for v in data[i:i + size * 3])
                    for i in range(0, len(data), size * 3)]
            lines.append(f"const uint8_t {name}[{size} * {size} * 3] = {{")
            lines.append(",\n".join("  " + r for r in rows))
            lines.append("};")
            lines.append("")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"Wrote {args.out} ({len(args.images)} image(s) x {len(SIZES)} sizes, RGB).")


if __name__ == "__main__":
    main()
